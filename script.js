// Function triggered by the "Analyze My Taste" button
function analyzeTaste() {
    const inputVal = document.getElementById("favMovie").value.trim();
    const resultsDiv = document.getElementById("results");
    const tasteAnalysisP = document.getElementById("tasteAnalysis");
    const gridDiv = document.getElementById("recommendationGrid");

    if (!inputVal) {
        alert("Please enter a favorite movie first!");
        return;
    }

    // Find which genre the entered movie belongs to
    let matchedGenre = "Drama"; // default fallback
    for (let genre in imdbTop250) {
        const found = imdbTop250[genre].movies.some(m => m.toLowerCase() === inputVal.toLowerCase());
        if (found) {
            matchedGenre = genre;
            break;
        }
    }

    // Display taste profile text
    tasteAnalysisP.innerHTML = `Based on your love for <strong>${inputVal}</strong>, your network connects into <strong>${matchedGenre}</strong>.<br><em>Definition: "${imdbTop250[matchedGenre].definition}"</em>`;

    // Clear previous results
    gridDiv.innerHTML = "";

    // Grab all movies for this genre, excluding the user input
    const allMoviesInGenre = imdbTop250[matchedGenre].movies;
    const moviesToRecommend = allMoviesInGenre.filter(movie => movie.toLowerCase() !== inputVal.toLowerCase());

    // 1. Add Network Stats HUD & Filter Bar
    const hudDiv = document.createElement("div");
    hudDiv.className = "network-hud";
    hudDiv.innerHTML = `
        <span>SECTOR: ${matchedGenre.toUpperCase()}</span>
        <span>LINKED NODES: ${moviesToRecommend.length}</span>
        <span>STATUS: ACTIVE/SYNCED</span>
    `;
    gridDiv.appendChild(hudDiv);

    // Filter input to search through network nodes live
    const filterInput = document.createElement("input");
    filterInput.type = "text";
    filterInput.placeholder = "🔍 Filter connected nodes...";
    filterInput.style.cssText = "width: 100%; padding: 8px; margin-bottom: 15px; background: #000; border: 1px solid #444; color: #fff; border-radius: 4px; z-index: 10; position: relative;";
    filterInput.addEventListener("input", (e) => {
        const query = e.target.value.toLowerCase();
        document.querySelectorAll(".network-node").forEach(node => {
            const title = node.getAttribute("data-movie").toLowerCase();
            node.style.display = title.includes(query) ? "block" : "none";
        });
    });
    gridDiv.appendChild(filterInput);

    // 2. Create SVG Canvas for Connection Lines
    const svgNs = "http://www.w3.org/2000/svg";
    const svg = document.createElementNS(svgNs, "svg");
    svg.setAttribute("class", "network-svg");
    gridDiv.appendChild(svg);

    // 3. Create Central Focus Hub Node
    const centerNode = document.createElement("div");
    centerNode.className = "center-node";
    centerNode.id = "hubNode";
    centerNode.innerHTML = `<strong>${inputVal}</strong><br><small style="color: #111;">(Core Film)</small>`;
    gridDiv.appendChild(centerNode);

    // 4. Render Recommendation Nodes (Click-to-Explore & Smart Saved States)
    const nodeElements = [];
    moviesToRecommend.forEach((movie) => {
        const isSaved = networkWatchlist.includes(movie);
        const btnText = isSaved ? "✓ Saved" : "+ Add to Watchlist";
        const btnBg = isSaved ? "#444" : "#f5c518";
        const btnColor = isSaved ? "#888" : "#000";

        const node = document.createElement("div");
        node.className = "network-node";
        node.setAttribute("data-movie", movie);
        node.innerHTML = `
            <div style="font-size: 13px; font-weight: bold; margin-bottom: 6px;">${movie}</div>
            <button onclick="event.stopPropagation(); addToWatchlist('${movie}')" style="background: ${btnBg}; color: ${btnColor}; border: none; padding: 4px 8px; cursor: pointer; font-weight: bold; border-radius: 3px; font-size: 11px;">${btnText}</button>
        `;
        
        // Click anywhere on the node card to make it the new core center film
        node.addEventListener("click", () => {
            document.getElementById("favMovie").value = movie;
            analyzeTaste();
        });

        gridDiv.appendChild(node);
        nodeElements.push(node);
    });

    // Show results and smoothly auto-scroll down to the network view
    resultsDiv.classList.remove("hidden");
    resultsDiv.scrollIntoView({ behavior: "smooth" });

    // 5. Draw Animated Network Lines
    setTimeout(() => {
        drawNetworkWeb(svg, centerNode, nodeElements);
    }, 50);
}

// Draw connection lines between center hub and recommendations
function drawNetworkWeb(svg, centerNode, nodeElements) {
    const gridRect = svg.parentElement.getBoundingClientRect();
    const centerRect = centerNode.getBoundingClientRect();

    const startX = centerRect.left + centerRect.width / 2 - gridRect.left;
    const startY = centerRect.top + centerRect.height / 2 - gridRect.top;

    const svgNs = "http://www.w3.org/2000/svg";

    nodeElements.forEach(node => {
        if (node.style.display === "none") return;

        const nodeRect = node.getBoundingClientRect();
        const endX = nodeRect.left + nodeRect.width / 2 - gridRect.left;
        const endY = nodeRect.top + nodeRect.height / 2 - gridRect.top;

        const line = document.createElementNS(svgNs, "line");
        line.setAttribute("x1", startX);
        line.setAttribute("y1", startY);
        line.setAttribute("x2", endX);
        line.setAttribute("y2", endY);
        line.setAttribute("stroke", "rgba(245, 197, 24, 0.4)");
        line.setAttribute("stroke-width", "1.5");
        line.setAttribute("stroke-dasharray", "4");
        svg.appendChild(line);
    });
}

// Auto-redraw connections on screen resize
window.addEventListener("resize", () => {
    const svg = document.querySelector(".network-svg");
    const centerNode = document.getElementById("hubNode");
    const nodeElements = document.querySelectorAll(".network-node");
    if (svg && centerNode && nodeElements.length > 0) {
        svg.innerHTML = "";
        drawNetworkWeb(svg, centerNode, Array.from(nodeElements));
    }
});

// Function triggered by "Surprise Me" button
function randomizeMovie() {
    const genres = Object.keys(imdbTop250);
    const randomGenre = genres[Math.floor(Math.random() * genres.length)];
    const moviesInGenre = imdbTop250[randomGenre].movies;
    const randomMovie = moviesInGenre[Math.floor(Math.random() * moviesInGenre.length)];
    
    document.getElementById("favMovie").value = randomMovie;
    analyzeTaste();
}

// Watchlist storage, persistence, and QoL helpers
function addToWatchlist(movieName) {
    if (!networkWatchlist.includes(movieName)) {
        networkWatchlist.push(movieName);
        saveAndRenderWatchlist();
        // Refresh active network nodes to update button states if visible
        const activeInput = document.getElementById("favMovie").value.trim();
        if (activeInput) analyzeTaste();
    } else {
        alert(`"${movieName}" is already in your watchlist!`);
    }
}

function removeFromWatchlist(movieName) {
    networkWatchlist = networkWatchlist.filter(m => m !== movieName);
    saveAndRenderWatchlist();
    const activeInput = document.getElementById("favMovie").value.trim();
    if (activeInput) analyzeTaste();
}

function clearWatchlist() {
    if (confirm("Clear your entire watchlist?")) {
        networkWatchlist = [];
        saveAndRenderWatchlist();
        const activeInput = document.getElementById("favMovie").value.trim();
        if (activeInput) analyzeTaste();
    }
}

function saveAndRenderWatchlist() {
    localStorage.setItem("networkWatchlist", JSON.stringify(networkWatchlist));
    updateWatchlistUI();
}

function updateWatchlistUI() {
    const container = document.getElementById("watchlistContainer");
    if (!container) return;

    if (networkWatchlist.length === 0) {
        container.innerHTML = `
            <h3>My Network Watchlist (0)</h3>
            <p style="font-size: 12px; color: #888;">No movies added yet. Click '+ Add to Watchlist' on recommendations!</p>
        `;
    } else {
        let listHTML = `
            <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 10px;">
                <h3 style="margin: 0;">My Network Watchlist (${networkWatchlist.length})</h3>
                <button onclick="clearWatchlist()" style="background: transparent; color: #ff4d4d; border: 1px solid #ff4d4d; border-radius: 3px; cursor: pointer; font-size: 11px; padding: 3px 8px;">Clear All</button>
            </div>
            <ul style="list-style-type: none; padding: 0; margin: 0;">
        `;
        networkWatchlist.forEach(movie => {
            listHTML += `<li style="padding: 6px 0; border-bottom: 1px solid #333; display: flex; justify-content: space-between; align-items: center;">
                <span>🎬 ${movie}</span>
                <button onclick="removeFromWatchlist('${movie}')" style="background: transparent; color: #ff4d4d; border: none; cursor: pointer; font-size: 11px;">Remove</button>
            </li>`;
        });
        listHTML += `</ul>`;
        container.innerHTML = listHTML;
    }
}